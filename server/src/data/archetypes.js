/**
 * Calcula o arquétipo predominante com base nas respostas do questionário
 */
export function calculateArchetype(answers) {
  const counts = {
    'o-enigma-magnetico': 0,
    'o-estrategista-silencioso': 0,
    'o-farol-empatico': 0,
    'o-visionario-instintivo': 0
  };

  if (!answers || typeof answers !== 'object') {
    return ARCHETYPES['o-enigma-magnetico'];
  }

  for (const val of Object.values(answers)) {
    if (counts[val] !== undefined) {
      counts[val] += 1;
    }
  }

  let highestArchetype = 'o-enigma-magnetico';
  let highestCount = -1;

  for (const [key, count] of Object.entries(counts)) {
    if (count > highestCount) {
      highestCount = count;
      highestArchetype = key;
    }
  }

  return ARCHETYPES[highestArchetype] || ARCHETYPES['o-enigma-magnetico'];
}
